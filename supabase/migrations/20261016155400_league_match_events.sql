-- ── 3. Helpers ───────────────────────────────────────────
-- The role under which the caller may OPERATE (append/correct) this
-- match, or null. Order: assigned official, competition manager, team
-- leader (only when the regulation says team_leaders_can_score).
create or replace function public.league_operator_role(m public.team_matches)
returns text language sql stable security definer set search_path = public as $$
  select case
    when public.is_match_official(m.id, array['referee']) then 'referee'
    when public.is_match_official(m.id, array['scorer'])  then 'scorer'
    when public.has_league_role(public.competition_league(m.competition_id), array['owner'], m.competition_id) then 'owner'
    when public.has_league_role(public.competition_league(m.competition_id), array['manager'], m.competition_id) then 'manager'
    when public.is_admin() then 'manager'
    when coalesce((public.competition_rules(m.competition_id)#>>'{homologation,team_leaders_can_score}')::boolean, false)
         and (public.is_team_leader(m.home_team_id) or public.is_team_leader(m.away_team_id)) then 'team_leader'
  end;
$$;

-- Can the caller homologate this match? (regulation homologation.authority)
create or replace function public.league_can_homologate(m public.team_matches)
returns text language sql stable security definer set search_path = public as $$
  select r.role from (values (1, 'owner'), (2, 'manager'), (3, 'referee')) r(ord, role)
   where r.role in (select jsonb_array_elements_text(public.competition_rules(m.competition_id)#>'{homologation,authority}'))
     and case r.role
           when 'referee' then public.is_match_official(m.id, array['referee'])
           else public.is_admin() or public.has_league_role(public.competition_league(m.competition_id), case when r.role = 'manager' then array['owner','manager'] else array[r.role] end, m.competition_id)
         end
   order by r.ord limit 1;
$$;

-- Is p_player in the homologated squad of p_team for the match's competition?
create or replace function public.league_in_squad(m public.team_matches, p_team uuid, p_player uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.competition_teams ct
                   join public.competition_squad_players sp on sp.registration_id = ct.id and sp.version = ct.homologated_squad_version
                  where ct.competition_id = m.competition_id and ct.team_id = p_team and sp.player_id = p_player);
$$;

-- Score from the effective log (definer: used by public payloads).
create or replace function public.league_match_score(p_match uuid)
returns table (home int, away int)
language sql stable security definer set search_path = public as $$
  select count(*) filter (where e.team_id = m.home_team_id)::int,
         count(*) filter (where e.team_id = m.away_team_id)::int
    from public.team_matches m
    left join public.team_match_events e
      on e.match_id = m.id and e.type in ('goal','own_goal') and e.action <> 'void'
     and not exists (select 1 from public.team_match_events s where s.supersedes = e.id)
   where m.id = p_match
   group by m.id;
$$;

-- ── 4. RPCs: events ──────────────────────────────────────

-- record_match_event(match, event) → {event_id, seq, duplicate, possible_duplicate}
-- event = {id, action?, supersedes?, type, team_id, player_id?, assist_player_id?,
--          sub_in_player_id?, period?, minute?, added_minute?, detail?, reason?, client_recorded_at?}
-- Who: league_operator_role(). When: match live or finished and not yet
-- submitted; after submission/homologation only the homologation
-- authority, with action 'correct'/'void' (source 'correction') — the
-- official numbers only change at the next homologation (L6).
create or replace function public.record_match_event(p_match_id uuid, p_event jsonb)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  m public.team_matches%rowtype; e jsonb := coalesce(p_event, '{}'::jsonb);
  v_id uuid; v_old public.team_match_events%rowtype; v_tgt public.team_match_events%rowtype;
  v_role text; v_action text := coalesce(e->>'action', 'add'); v_type text := e->>'type';
  v_team uuid; v_player uuid; v_assist uuid; v_subin uuid; v_other uuid; v_rules jsonb;
  v_post boolean; v_seq int; v_dup boolean;
begin
  perform public.league_rpc_begin();
  begin v_id := (e->>'id')::uuid; exception when others then v_id := null; end;
  if v_id is null then raise exception 'league:event_id_required'; end if;
  m := public.league_lock_match(p_match_id);

  -- Idempotent replay (checked before any permission/state change so an
  -- offline retry after the match ended still answers cleanly).
  select * into v_old from public.team_match_events where id = v_id;
  if found then
    if v_old.match_id = m.id and v_old.type = coalesce(v_type, v_old.type) and v_old.action = v_action
       and v_old.team_id is not distinct from (e->>'team_id')::uuid and v_old.player_id is not distinct from (e->>'player_id')::uuid
       and v_old.assist_player_id is not distinct from (e->>'assist_player_id')::uuid
       and v_old.supersedes is not distinct from (e->>'supersedes')::uuid then
      return jsonb_build_object('event_id', v_old.id, 'seq', v_old.seq, 'duplicate', true);
    end if;
    raise exception 'league:event_id_conflict';
  end if;

  v_post := m.result_status in ('submitted','homologated');
  if v_post then
    v_role := public.league_can_homologate(m);
    if v_role is null then raise exception 'league:not_authority' using errcode = '42501'; end if;
    if v_action = 'add' and coalesce(e->>'source', '') <> 'correction' then raise exception 'league:sumula_closed'; end if;
  else
    v_role := public.league_operator_role(m);
    if v_role is null then raise exception 'league:not_operator' using errcode = '42501'; end if;
    if m.match_status not in ('live','finished') then raise exception 'league:match_not_live'; end if;
  end if;
  if v_post and coalesce(btrim(e->>'reason'), '') = '' then raise exception 'league:reason_required'; end if;

  -- Correction / annulment target.
  if v_action in ('correct','void') then
    select * into v_tgt from public.team_match_events where id = (e->>'supersedes')::uuid and match_id = m.id;
    if not found then raise exception 'league:event_not_found'; end if;
    if v_tgt.action = 'void' or exists (select 1 from public.team_match_events where supersedes = v_tgt.id) then
      raise exception 'league:stale_event';
    end if;
    if coalesce(btrim(e->>'reason'), '') = '' then raise exception 'league:reason_required'; end if;
    if v_action = 'void' then
      v_type := v_tgt.type; v_team := v_tgt.team_id; v_player := v_tgt.player_id; v_assist := null; v_subin := v_tgt.sub_in_player_id;
    end if;
  elsif v_action <> 'add' then
    raise exception 'league:invalid_event';
  end if;

  if v_action <> 'void' then
    v_team := (e->>'team_id')::uuid; v_player := (e->>'player_id')::uuid;
    v_assist := (e->>'assist_player_id')::uuid; v_subin := (e->>'sub_in_player_id')::uuid;
    if v_type is null or v_type not in ('goal','own_goal','yellow','second_yellow','red','sub','period') then
      raise exception 'league:invalid_event' using detail = coalesce(v_type, 'null type');
    end if;
    if v_type <> 'period' and (v_team is null or v_team not in (m.home_team_id, m.away_team_id)) then
      raise exception 'league:invalid_event' using detail = 'team';
    end if;
    v_other := case when v_team = m.home_team_id then m.away_team_id else m.home_team_id end;
    v_rules := public.competition_rules(m.competition_id);
    -- Squad checks: goal/cards/subs → the team's squad; own goal → the OPPONENT's.
    if v_player is not null and v_type <> 'period'
       and not public.league_in_squad(m, case when v_type = 'own_goal' then v_other else v_team end, v_player) then
      raise exception 'league:player_not_in_squad';
    end if;
    if v_type in ('yellow','second_yellow','red','sub') and v_player is null then raise exception 'league:player_required'; end if;
    if v_assist is not null then
      if v_rules->>'assists' = 'none' then raise exception 'league:assists_disabled'; end if;
      if not public.league_in_squad(m, v_team, v_assist) then raise exception 'league:player_not_in_squad'; end if;
    end if;
    if v_subin is not null and not public.league_in_squad(m, v_team, v_subin) then raise exception 'league:player_not_in_squad'; end if;
  end if;

  update public.team_matches set seq = seq + 1, updated_at = now() where id = m.id returning seq into v_seq;
  insert into public.team_match_events (id, match_id, seq, action, supersedes, type, team_id, player_id, assist_player_id,
                                        sub_in_player_id, period, minute, added_minute, detail, reason, source,
                                        recorded_by, recorded_role, client_recorded_at)
  values (v_id, m.id, v_seq, v_action, (e->>'supersedes')::uuid, v_type, v_team, v_player, v_assist,
          v_subin, coalesce(e->>'period', case when v_action = 'void' then v_tgt.period end),
          coalesce((e->>'minute')::int, case when v_action = 'void' then v_tgt.minute end), (e->>'added_minute')::int,
          coalesce(e->'detail', '{}'::jsonb), nullif(btrim(e->>'reason'), ''),
          case when v_post then 'correction' else coalesce(nullif(e->>'source', ''), 'live') end,
          public.my_player_id(), v_role, (e->>'client_recorded_at')::timestamptz);

  -- Non-blocking hint: same type/team/player in the last 60s from someone else.
  v_dup := v_action = 'add' and exists (
    select 1 from public.team_match_events_effective x
     where x.match_id = m.id and x.id <> v_id and x.type = v_type and x.team_id is not distinct from v_team
       and x.player_id is not distinct from v_player and x.recorded_at > now() - interval '60 seconds'
       and x.recorded_by is distinct from public.my_player_id());
  perform public.league_audit(public.competition_league(m.competition_id), 'event_' || v_action,
    jsonb_build_object('event_id', v_id, 'type', v_type, 'seq', v_seq, 'reason', e->>'reason'), m.competition_id, m.id);
  return jsonb_build_object('event_id', v_id, 'seq', v_seq, 'duplicate', false, 'possible_duplicate', v_dup);
exception when invalid_text_representation then raise exception 'league:invalid_event';
end $$;

-- ── 5. RPCs: lifecycle ───────────────────────────────────
-- set_match_phase(match, 'live'|'finished'|'submitted', expected_seq, note) → {match_status, result_status, seq}
--   live      : scheduled → live (operator; not before kickoff − 2h)
--   finished  : live → finished, result_status provisional (operator)
--   submitted : finished/provisional → submitted (referee or manager): the
--               súmula goes to review. Ending ≠ homologating (brief §8).
create or replace function public.set_match_phase(p_match_id uuid, p_phase text, p_expected_seq int, p_note text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare m public.team_matches%rowtype; v_role text;
begin
  perform public.league_rpc_begin();
  m := public.league_lock_match(p_match_id);
  v_role := public.league_operator_role(m);
  if v_role is null then raise exception 'league:not_operator' using errcode = '42501'; end if;
  if p_expected_seq is distinct from m.seq then raise exception 'league:stale_seq'; end if;
  if p_phase = 'live' then
    if m.match_status <> 'scheduled' then raise exception 'league:invalid_transition'; end if;
    if m.kickoff_at > now() + interval '2 hours' then raise exception 'league:too_early'; end if;
    update public.team_matches set match_status = 'live', started_at = now(), seq = seq + 1, updated_at = now()
     where id = m.id returning * into m;
  elsif p_phase = 'finished' then
    if m.match_status <> 'live' then raise exception 'league:invalid_transition'; end if;
    update public.team_matches set match_status = 'finished', result_status = 'provisional', ended_at = now(),
           seq = seq + 1, updated_at = now() where id = m.id returning * into m;
  elsif p_phase = 'submitted' then
    if v_role not in ('referee','owner','manager') then raise exception 'league:not_allowed' using errcode = '42501'; end if;
    if m.match_status <> 'finished' or m.result_status <> 'provisional' then raise exception 'league:invalid_transition'; end if;
    update public.team_matches set result_status = 'submitted', status_reason = left(p_note, 500), seq = seq + 1, updated_at = now()
     where id = m.id returning * into m;
  else
    raise exception 'league:invalid_transition';
  end if;
  perform public.league_audit(public.competition_league(m.competition_id), 'match_' || p_phase,
    jsonb_build_object('seq', m.seq, 'role', v_role), m.competition_id, m.id);
  return jsonb_build_object('match_id', m.id, 'match_status', m.match_status, 'result_status', m.result_status, 'seq', m.seq);
end $$;

-- ── 6. Read RPCs ─────────────────────────────────────────
-- match_live(match, key) → {match, score{home, away, state}, timeline[], officials[], my_role}
-- anon + authenticated, same visibility rule as competition_matches().
-- score.state: 'live' | 'provisional' | 'in_review' | 'homologated' (the UI
-- must label everything but 'homologated' as unofficial — brief §8).
-- Once homologated the OFFICIAL score is returned (it can differ from the
-- live log while a post-homologation correction awaits re-homologation:
-- pending_rehomologation = true).
create or replace function public.match_live(p_match_id uuid, p_key text default null)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare m public.team_matches%rowtype; v_c public.competitions%rowtype; v_g public.leagues%rowtype; v_vis text;
        v_h int; v_a int; v_youth boolean;
begin
  select * into m from public.team_matches where id = p_match_id and source_type = 'competition';
  if not found then return null; end if;
  select * into v_c from public.competitions where id = m.competition_id;
  select * into v_g from public.leagues where id = v_c.league_id;
  v_vis := coalesce(v_c.visibility, v_g.visibility);
  if not ((public.my_player_id() is not null and public.can_see_match(m.id))
          or (v_c.status <> 'draft' and v_g.status <> 'draft'
              and (v_vis in ('public','unlisted') or p_key in (v_c.view_key, v_g.view_key)))) then
    return null;
  end if;
  v_youth := coalesce((select youth from public.league_categories where id = v_c.category_id), false);
  select s.home, s.away into v_h, v_a from public.league_match_score(m.id) s;
  return jsonb_build_object(
    'match', jsonb_build_object('id', m.id, 'competition_id', m.competition_id, 'round_id', m.round_id,
               'home_team_id', m.home_team_id, 'away_team_id', m.away_team_id, 'kickoff_at', m.kickoff_at,
               'timezone', m.timezone, 'venue_name', m.venue_name, 'match_status', m.match_status,
               'result_status', m.result_status, 'seq', m.seq, 'started_at', m.started_at, 'ended_at', m.ended_at),
    'score', jsonb_build_object(
               'home', case when m.result_status = 'homologated' then m.official_home_score else v_h end,
               'away', case when m.result_status = 'homologated' then m.official_away_score else v_a end,
               'state', case m.result_status when 'homologated' then 'homologated' when 'submitted' then 'in_review'
                                             when 'provisional' then 'provisional'
                                             else case when m.match_status = 'live' then 'live' else 'none' end end,
               'pending_rehomologation', m.result_status = 'homologated'
                                         and (v_h is distinct from m.official_home_score or v_a is distinct from m.official_away_score)),
    'timeline', coalesce((select jsonb_agg(jsonb_build_object(
                  'id', e.id, 'type', e.type, 'team_id', e.team_id, 'period', e.period, 'minute', e.minute,
                  'added_minute', e.added_minute, 'detail', e.detail, 'corrected', e.action = 'correct',
                  'player', case when e.player_id is null then null when v_youth then (select upper(left(p.name, 1)) || '.' from public.players p where p.id = e.player_id)
                                 else public.league_person_name(e.player_id) end,
                  'player_id', e.player_id,
                  'assist', case when e.assist_player_id is null then null when v_youth then (select upper(left(p.name, 1)) || '.' from public.players p where p.id = e.assist_player_id)
                                 else public.league_person_name(e.assist_player_id) end,
                  'assist_player_id', e.assist_player_id)
                  order by e.period nulls first, e.minute nulls last, e.seq)
                  from public.team_match_events_effective e where e.match_id = m.id), '[]'::jsonb),
    'officials', coalesce((select jsonb_agg(jsonb_build_object('role', o.role, 'name', public.league_person_name(o.player_id)))
                             from public.team_match_officials o where o.match_id = m.id), '[]'::jsonb),
    'my_role', case when public.my_player_id() is null then null else public.league_operator_role(m) end,
    'can_homologate', public.my_player_id() is not null and public.league_can_homologate(m) is not null);
end $$;

-- match_event_history(match) → {items:[every row incl. superseded/void, with reason + who]}
-- Staff of the competition and members of either team (audit trail; brief §8).
create or replace function public.match_event_history(p_match_id uuid)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare m public.team_matches%rowtype;
begin
  select * into m from public.team_matches where id = p_match_id and source_type = 'competition';
  if not found or not (public.is_competition_staff(m.competition_id) or public.is_team_member(m.home_team_id)
                       or public.is_team_member(m.away_team_id)) then
    raise exception 'league:match_not_found';
  end if;
  return jsonb_build_object('items', coalesce((select jsonb_agg(jsonb_build_object(
      'id', e.id, 'seq', e.seq, 'action', e.action, 'supersedes', e.supersedes, 'type', e.type, 'team_id', e.team_id,
      'player_id', e.player_id, 'assist_player_id', e.assist_player_id, 'minute', e.minute, 'reason', e.reason,
      'source', e.source, 'recorded_by', public.league_person_name(e.recorded_by), 'recorded_role', e.recorded_role,
      'recorded_at', e.recorded_at,
      'effective', e.action <> 'void' and not exists (select 1 from public.team_match_events s where s.supersedes = e.id))
      order by e.seq) from public.team_match_events e where e.match_id = m.id), '[]'::jsonb));
end $$;

-- ── 7. EXECUTE grants ────────────────────────────────────
do $$
declare f text;
begin
  foreach f in array array[
    'public.record_match_event(uuid, jsonb)', 'public.set_match_phase(uuid, text, int, text)',
    'public.match_event_history(uuid)'
  ] loop
    execute format('revoke execute on function %s from public, anon', f);
    execute format('grant execute on function %s to authenticated, service_role', f);
  end loop;
  execute 'revoke execute on function public.match_live(uuid, text) from public';
  execute 'grant execute on function public.match_live(uuid, text) to anon, authenticated, service_role';
  foreach f in array array[
    'public.league_operator_role(public.team_matches)', 'public.league_can_homologate(public.team_matches)',
    'public.league_in_squad(public.team_matches, uuid, uuid)', 'public.league_match_score(uuid)'
  ] loop
    execute format('revoke execute on function %s from public, anon, authenticated', f);
    execute format('grant execute on function %s to service_role', f);
  end loop;
end $$;

