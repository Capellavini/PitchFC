-- Effective log. security_invoker ⇒ the caller's RLS on the base table applies.
create or replace view public.team_match_events_effective with (security_invoker = true) as
  select e.* from public.team_match_events e
   where e.action <> 'void'
     and not exists (select 1 from public.team_match_events s where s.supersedes = e.id);

