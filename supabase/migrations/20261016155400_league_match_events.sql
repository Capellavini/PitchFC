-- ─────────────────────────────────────────────────────────
-- PITCH Ligas Fase 2 — migration L3b (design plan PR L5): the append-only match event log
-- (súmula ao vivo) + match lifecycle + live projections.
--
-- Source: docs/ligas-draft-sql/05_match_events.sql. Depends on 01–04.
-- Plan: docs/LIGAS-FASE2-PLAN.md §3.7 (the core), §3.8.
--
-- Model
--   • team_match_events is APPEND-ONLY. Rows are never updated or deleted
--     (trigger). A correction is a new row with action = 'correct' that
--     `supersedes` the old one; an annulment is a row with action = 'void'.
--     Both REQUIRE a reason. unique(supersedes) ⇒ an event has at most one
--     successor, so two operators correcting the same goal at once cannot
--     both win: the second gets league:stale_event (no silent overwrite).
--   • id is generated by the CLIENT (uuid v4 at tap time). Re-sending the
--     same id is idempotent (same content → duplicate = true; different
--     content → league:event_id_conflict). Offline retries never double a goal.
--   • team_matches.seq is bumped (under the match row lock) by every append
--     and lifecycle transition; each event stores the seq it produced.
--     Appends do not require the caller's seq (goals by two operators are
--     both valid and commute); lifecycle actions (end, submit, homologate)
--     DO require it, so nobody homologates a log they have not seen.
--   • Effective log = rows with action <> 'void' that nothing supersedes.
--     Score, timeline, player stats, discipline and (later) fantasy are all
--     computed from it — there is no second editable number anywhere.
--   • Cards exist ONLY here, and this table only accepts COMPETITION matches
--     (owner, 2026-10-16): the group Matchday (games.live_matchday →
--     matchdays.summary → player_group_memberships) never sees a card, and
--     Rivals friendlies keep their counts-only stats.
-- ─────────────────────────────────────────────────────────

alter table public.team_matches
  add column if not exists started_at timestamptz,
  add column if not exists ended_at   timestamptz;

-- ── 1. Event log ─────────────────────────────────────────
create table if not exists public.team_match_events (
  id                 uuid primary key,                       -- client-generated
  match_id           uuid not null references public.team_matches(id) on delete cascade,
  seq                int  not null,                          -- team_matches.seq after this append
  action             text not null default 'add' check (action in ('add','correct','void')),
  supersedes         uuid references public.team_match_events(id) on delete restrict,
  type               text not null check (type in ('goal','own_goal','yellow','second_yellow','red','sub','period')),
  -- goal / own_goal: the team that BENEFITS (same convention as the shared
  -- core, src/lib/core/standings.js). Cards / subs: the player's team.
  team_id            uuid references public.teams(id) on delete restrict,
  player_id          uuid references public.players(id) on delete restrict,  -- null = author unknown (allowed)
  assist_player_id   uuid references public.players(id) on delete restrict,
  sub_in_player_id   uuid references public.players(id) on delete restrict,  -- type 'sub': player_id leaves
  period             text check (period is null or period in ('1H','2H','ET1','ET2')),
  minute             int  check (minute is null or minute between 0 and 200),
  added_minute       int  check (added_minute is null or added_minute between 0 and 30),
  -- type 'period': {"mark": "start"|"end"}; goal: {"penalty": true} (in-game penalty, still a goal)
  detail             jsonb not null default '{}'::jsonb,
  reason             text check (reason is null or char_length(reason) <= 500),
  source             text not null default 'live' check (source in ('live','sumula','correction')),
  recorded_by        uuid references public.players(id) on delete set null,
  recorded_role      text,                                    -- 'scorer' | 'referee' | 'manager' | 'owner' | 'team_leader'
  recorded_at        timestamptz not null default now(),
  client_recorded_at timestamptz,
  constraint team_match_events_supersedes_key unique (supersedes),
  constraint team_match_events_seq_key unique (match_id, seq),
  constraint team_match_events_correction_reason_check check (action = 'add' or (supersedes is not null and coalesce(btrim(reason), '') <> '')),
  constraint team_match_events_add_check check (action <> 'add' or supersedes is null),
  constraint team_match_events_assist_check check (assist_player_id is null or (type = 'goal' and assist_player_id is distinct from player_id)),
  constraint team_match_events_team_check check (type = 'period' or team_id is not null),
  constraint team_match_events_sub_check check ((type = 'sub') = (sub_in_player_id is not null) or action = 'void')
);
create index if not exists team_match_events_match_idx on public.team_match_events (match_id, seq);
create index if not exists team_match_events_player_idx on public.team_match_events (player_id) where player_id is not null;

